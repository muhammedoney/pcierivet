# Generate the 8b/10b encode table used by rivet_phy_8b10b.sv.
# Bit order matches the PCS: [9:4] = abcdei, [3:0] = fghj, a is the MSB of abcdei.

D6_NEG = [
    0b100111, 0b011101, 0b101101, 0b110001, 0b110101, 0b101001, 0b011001, 0b111000,
    0b111001, 0b100101, 0b010101, 0b110100, 0b001101, 0b101100, 0b011100, 0b010111,
    0b011011, 0b100011, 0b010011, 0b110010, 0b001011, 0b101010, 0b011010, 0b111010,
    0b110011, 0b100110, 0b010110, 0b110110, 0b001110, 0b101110, 0b011110, 0b101011,
]
D4_NEG = [0b1011, 0b1001, 0b0101, 0b1100, 0b1101, 0b1010, 0b0110, 0b1110]
D4_ALT = [0b0111, 0b1000]  # RD-, RD+


def disp(code, width):
    ones = bin(code).count("1")
    return ones - (width - ones)


def other6(n, code):
    if n == 7:
        return 0b000111 if code == 0b111000 else 0b111000
    if disp(code, 6) == 0:
        return code
    return (~code) & 0x3F


def other4(n, code, alt):
    if n == 7 and alt:
        return 0b1000 if code == 0b0111 else 0b0111
    if n == 7 and not alt:
        return 0b0001 if code == 0b1110 else 0b1110
    if disp(code, 4) == 0:
        return code
    return (~code) & 0xF


def pick6(n, rd_neg):
    neg = D6_NEG[n]
    return neg if rd_neg else other6(n, neg)


def pick4(n, rd_neg, alt):
    if n == 7 and alt:
        return D4_ALT[0] if rd_neg else D4_ALT[1]
    neg = D4_NEG[n]
    return neg if rd_neg else other4(n, neg, False)


def use_alt(abcdei):
    # Dx.7 alternate avoids a run of five when the 6b ends in three equal bits
    # and already has nonzero disparity.
    return abcdei in (0b111000, 0b000111, 0b110000, 0b001111)


# Full 10-bit K codes, (RD-, RD+), abcdei in the high 6 bits.
K10 = {
    0x1C: (0b0011110100, 0b1100001011),
    0x3C: (0b0011111001, 0b1100000110),
    0x5C: (0b0011110101, 0b1100001010),
    0x7C: (0b0011110011, 0b1100001100),
    0x9C: (0b0011110010, 0b1100001101),
    0xBC: (0b0011111010, 0b1100000101),
    0xDC: (0b0011110110, 0b1100001001),
    0xFC: (0b0011111000, 0b1100000111),
    0xF7: (0b1110101000, 0b0001010111),
    0xFB: (0b1101101000, 0b0010010111),
    0xFD: (0b1011101000, 0b0100010111),
    0xFE: (0b0111101000, 0b1000010111),
}


def apply_rd(code, width, rd_neg):
    d = disp(code, width)
    if d > 0:
        rd_neg = False
    elif d < 0:
        rd_neg = True
    return rd_neg


def encode(byte, k, rd_neg):
    edcba = byte & 0x1F
    hgf = (byte >> 5) & 0x7
    if k:
        if byte not in K10:
            return None
        code = K10[byte][0] if rd_neg else K10[byte][1]
        rd_mid = apply_rd((code >> 4) & 0x3F, 6, rd_neg)
        rd_next = apply_rd(code & 0xF, 4, rd_mid)
        return code, rd_next
    else:
        six = pick6(edcba, rd_neg)
        rd_mid = apply_rd(six, 6, rd_neg)
        alt = (hgf == 7) and use_alt(six)
        four = pick4(hgf, rd_mid, alt)
    rd_next = apply_rd(four, 4, rd_mid)
    code = (six << 4) | four
    return code, (not rd_next) if False else rd_next


def main():
    # Fix the K four selection by re-running encode carefully.
    fails = 0
    table = {}
    for k in (0, 1):
        for b in range(256):
            for rd in (True, False):
                try:
                    got = encode(b, k, rd)
                except Exception:
                    got = None
                if k and got is None:
                    continue
                if got is None:
                    fails += 1
                    continue
                code, rd_next = got
                table[(b, k, rd)] = (code, rd_next)
    # K28.5 RD-
    k285 = table[(0xBC, 1, True)][0]
    d102 = table[(0x4A, 0, True)][0]
    print(f"K28.5 RD- {k285:010b} expect 0011111010")
    print(f"D10.2 {d102:010b}")
    if k285 != 0b0011111010:
        raise SystemExit("K28.5 mismatch")
    # round trip data
    dec = {}
    for (b, k, rd), (code, rd_next) in table.items():
        dec.setdefault(code, set()).add((b, k))
    bad = 0
    for b in range(256):
        rd = True
        for _ in range(4):
            code, rd = table[(b, 0, rd)]
            cands = dec[code]
            if (b, 0) not in cands:
                bad += 1
    print("roundtrip mismatches", bad, "encode fails", fails)
    # emit SV
    lines = []
    lines.append("// Generated by scripts/gen_8b10b_table.py. Do not edit by hand.")
    lines.append("function automatic logic [9:0] rivet_phy_enc10(")
    lines.append("  input logic [7:0] d, input logic k, input logic rd_neg,")
    lines.append("  output logic rd_neg_n, output logic invalid);")
    lines.append("  invalid = 1'b0;")
    lines.append("  rd_neg_n = rd_neg;")
    lines.append("  rivet_phy_enc10 = 10'h0;")
    lines.append("  if (k) begin")
    lines.append("    unique case ({rd_neg, d})")
    for (b, k, rd), (code, rd_next) in sorted(table.items()):
        if not k:
            continue
        lines.append(
            f"      {{1'b{int(rd)}, 8'h{b:02X}}}: begin rivet_phy_enc10 = 10'b{code:010b}; rd_neg_n = 1'b{int(rd_next)}; end"
        )
    lines.append("      default: invalid = 1'b1;")
    lines.append("    endcase")
    lines.append("  end else begin")
    lines.append("    unique case ({rd_neg, d})")
    for (b, k, rd), (code, rd_next) in sorted(table.items()):
        if k:
            continue
        lines.append(
            f"      {{1'b{int(rd)}, 8'h{b:02X}}}: begin rivet_phy_enc10 = 10'b{code:010b}; rd_neg_n = 1'b{int(rd_next)}; end"
        )
    lines.append("      default: invalid = 1'b1;")
    lines.append("    endcase")
    lines.append("  end")
    lines.append("endfunction")
    # code -> (data, k, rd_mask bit0=RD-, bit1=RD+, rd_next_neg, rd_next_pos)
    by_code = {}
    for (b, kflag, rd), (code, rd_next) in table.items():
        slot = by_code.setdefault(code, [b, kflag, 0, True, False])
        if slot[0] != b or slot[1] != kflag:
            raise SystemExit(f"code collision {code:010b}")
        if rd:
            slot[2] |= 1
            slot[3] = rd_next
        else:
            slot[2] |= 2
            slot[4] = rd_next
    lines.append("")
    lines.append("function automatic void rivet_phy_dec10(")
    lines.append("  input logic [9:0] code, input logic rd_neg,")
    lines.append("  output logic [7:0] d, output logic k, output logic rd_neg_n,")
    lines.append("  output logic code_err, output logic disp_err);")
    lines.append("  d = '0; k = 1'b0; rd_neg_n = rd_neg;")
    lines.append("  code_err = 1'b0; disp_err = 1'b0;")
    lines.append("  unique case (code)")
    for code, (b, kflag, mask, rd_n_neg, rd_n_pos) in sorted(by_code.items()):
        lines.append(
            f"    10'b{code:010b}: begin d = 8'h{b:02X}; k = 1'b{kflag}; "
            f"if (rd_neg) begin rd_neg_n = 1'b{int(rd_n_neg)}; disp_err = 1'b{int((mask & 1) == 0)}; end "
            f"else begin rd_neg_n = 1'b{int(rd_n_pos)}; disp_err = 1'b{int((mask & 2) == 0)}; end end"
        )
    lines.append("    default: code_err = 1'b1;")
    lines.append("  endcase")
    lines.append("endfunction")
    open("rtl/phy/rivet_phy_8b10b_enc.svh", "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote enc", len(table), "codes", len(by_code))


if __name__ == "__main__":
    main()
